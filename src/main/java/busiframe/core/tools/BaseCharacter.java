package busiframe.core.tools;

/**
 * 文字列汎用インターフェースクラス<br>
 * @since 2024/11/16
 * @version 1.00 新規作成
 */
public interface BaseCharacter {

	// 文字列
	/** 改行 */
	public final String LF = "\n";
	/** 空白 */
	public final String SP = " ";
	/** ダブルクォーテーション */
	public final String DQ = "\"";
	/** シングルクォーテーション */
	public final String SQ = "'";
	/** タブ */
	public final String TB = "\t";
	public final String T2 = "\t\t";
	public final String T3 = "\t\t\t";
	public final String T4 = "\t\t\t\t";
}
